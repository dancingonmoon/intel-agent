_RSS_LINK_RE = re.compile(
    r'<link[^>]+(?:type=["\']application/(?:rss|atom)\+xml["\'][^>]*href=["\']([^"\']+)|href=["\']([^"\']+)["\'][^>]*type=["\']application/(?:rss|atom)\+xml)',
    re.IGNORECASE,
)
_COMMON_FEEDS = ("/rss", "/rss.xml", "/feed", "/feed/", "/?feed=rss2")


@dataclass(slots=True)
class SourceMetric:
    source: str
    runs: int = 0
    ok_runs: int = 0
    fetched: int = 0
    selected: int = 0
    good: int = 0
    bad: int = 0
    last_error: str = ""
    verdict: str = "keep"

    def as_dict(self) -> dict:
        return {
            "source": self.source,
            "runs": self.runs,
            "ok_runs": self.ok_runs,
            "fetched": self.fetched,
            "selected": self.selected,
            "good": self.good,
            "bad": self.bad,
            "last_error": self.last_error[:200],
            "verdict": self.verdict,
        }


def source_metrics(store: Store, topic: str, runs: int = 10, days: int = 30) -> list[SourceMetric]:
    run_ids = [
        row["run_id"]
        for row in store.conn.execute(
            "SELECT DISTINCT run_id FROM source_health WHERE run_id LIKE ? "
            "ORDER BY run_id DESC LIMIT ?",
            (f"%-{topic}", runs),
        )
    ]
    metrics: dict[str, SourceMetric] = {}
    if run_ids:
        marks = ",".join("?" for _ in run_ids)
        rows = store.conn.execute(
            f"""
            SELECT source, COUNT(*) AS runs,
                   SUM(CASE WHEN ok THEN 1 ELSE 0 END) AS ok_runs,
                   SUM(count) AS fetched,
                   MAX(CASE WHEN error IS NOT NULL AND error <> '' THEN error END) AS last_error
            FROM source_health
            WHERE run_id IN ({marks})
            GROUP BY source
            """,
            run_ids,
        ).fetchall()
        for row in rows:
            metrics[row["source"]] = SourceMetric(
                source=row["source"],
                runs=int(row["runs"]),
                ok_runs=int(row["ok_runs"] or 0),
                fetched=int(row["fetched"] or 0),
                last_error=row["last_error"] or "",
            )
    for source, values in store.selection_counts(days=days).items():
        metric = metrics.setdefault(source, SourceMetric(source=source))
        metric.selected = int(values.get("selected", 0))
    for source, values in store.feedback_counts(days=days).items():
        metric = metrics.setdefault(source, SourceMetric(source=source))
        metric.good = int(values.get("good", 0))
        metric.bad = int(values.get("bad", 0))

    for metric in metrics.values():
        error = metric.last_error.lower()
        flaky = any(token in error for token in ("selector drift", "captcha", "cdp discovery"))
        if metric.runs >= 3 and metric.ok_runs == 0:
            metric.verdict = "remove"
        elif metric.bad >= 3 and metric.good == 0:
            metric.verdict = "remove"
        elif metric.runs >= 8 and metric.selected == 0 and metric.fetched > 0:
            metric.verdict = "watch"
        elif metric.runs and metric.ok_runs / metric.runs < 0.6:
            metric.verdict = "watch"
        elif flaky:
            metric.verdict = "watch"
        elif metric.selected >= 2 and metric.good >= 1:
            metric.verdict = "expand"
        else:
            metric.verdict = "keep"
    order = {"remove": 0, "watch": 1, "expand": 2, "keep": 3}
    return sorted(metrics.values(), key=lambda m: (order.get(m.verdict, 9), -m.selected, m.source))


def overlay_path(topic_id: str) -> Path:
    return TOPICS_DIR / f"{topic_id}.sources.yaml"


def load_overlay(topic_id: str) -> dict:
    path = overlay_path(topic_id)
    if not path.exists():
        return {"add": {"rss": [], "telegram_channels": []}, "disable": {"sources": []}}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    data.setdefault("add", {}).setdefault("rss", [])
    data.setdefault("add", {}).setdefault("telegram_channels", [])
    data.setdefault("disable", {}).setdefault("sources", [])
    return data


def _write_overlay(topic_id: str, data: dict) -> Path:
    path = overlay_path(topic_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(data, allow_unicode=True, sort_keys=False)
    path.write_text(
        "# Generated by intel source add/disable/learn. Base topic YAML is never edited.\n" + body,
        encoding="utf-8",
    )
    return path


def add_sources(topic_id: str, *, rss_urls: list[str] | None = None, channels: list[str] | None = None) -> Path:
    data = load_overlay(topic_id)
    for url in rss_urls or []:
        if url and url not in data["add"]["rss"]:
            data["add"]["rss"].append(url)
    for channel in channels or []:
        channel = channel.lstrip("@")
        if channel and channel not in data["add"]["telegram_channels"]:
            data["add"]["telegram_channels"].append(channel)
    return _write_overlay(topic_id, data)


def disable_sources(topic_id: str, sources: list[str]) -> Path:
    data = load_overlay(topic_id)
    for source in sources:
        if source and source not in data["disable"]["sources"]:
            data["disable"]["sources"].append(source)
    return _write_overlay(topic_id, data)


def enable_sources(topic_id: str, sources: list[str]) -> Path:
    data = load_overlay(topic_id)
    data["disable"]["sources"] = [x for x in data["disable"]["sources"] if x not in set(sources)]
    return _write_overlay(topic_id, data)


def test_rss(url: str, settings: dict) -> tuple[bool, int, str]:
    result = rss.fetch_generic_rss(url, settings, lang="ru")
    return result.ok, len(result.articles), result.error or ""


def test_telegram(channel: str, settings: dict) -> tuple[bool, int, str]:
    result = telegram.fetch_channel(channel.lstrip("@"), settings)
    return result.ok, len(result.articles), result.error or ""


def _candidate_feed(domain: str, settings: dict) -> tuple[str, int] | None:
    base = f"https://{domain}"
    page = fetch(base, settings)
    candidates: list[str] = []
    if page.ok:
        for match in _RSS_LINK_RE.finditer(page.text):
            href = match.group(1) or match.group(2) or ""
            if href:
                candidates.append(href if href.startswith("http") else f"https://{domain}{href}")
    candidates.extend(f"https://{domain}{path}" for path in _COMMON_FEEDS)
    seen = set()
    for candidate in candidates:
        if candidate in seen:
            continue
        seen.add(candidate)
        result = rss.fetch_generic_rss(candidate, settings, lang="ru")
        if result.ok and result.articles:
            return candidate, len(result.articles)
    return None


def suggest_sources(store: Store, topic_id: str, settings: dict, days: int = 30, limit: int = 8) -> list[dict]:
    known = {str(x) for x in load_overlay(topic_id).get("add", {}).get("rss", [])}
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).date().isoformat()
    rows = store.conn.execute(
        """
        SELECT canonical_url, source FROM report_selections
        WHERE topic = ? AND report_date >= ?
        ORDER BY report_date DESC
        LIMIT 200
        """,
        (topic_id, cutoff),
    ).fetchall()
    domains: dict[str, int] = {}
    channels: dict[str, int] = {}
    for row in rows:
        parsed = urlparse(str(row["canonical_url"] or ""))
        host = (parsed.hostname or "").lower()
        if host in ("t.me", "telegram.me") and parsed.path:
            channel = parsed.path.strip("/").split("/")[0]
            if channel:
                channels[channel] = channels.get(channel, 0) + 1
            continue
        if not host or host.endswith(("google.com", "bing.com", "yandex.ru", "dzen.ru")):
            continue
        if any(host.endswith(value) for value in ("x.com", "twitter.com", "t.me")):
            continue
        domains[host] = domains.get(host, 0) + 1

    suggestions: list[dict] = []
    for host, count in sorted(domains.items(), key=lambda item: -item[1])[:limit]:
        if any(host in url for url in known):
            continue
        found = _candidate_feed(host, settings)
        if found:
            suggestions.append(
                {"kind": "rss", "value": found[0], "items": found[1], "reason": f"cited {count}x in selected reports"}
            )
    for channel, count in sorted(channels.items(), key=lambda item: -item[1])[:limit]:
        ok, count_items, error = test_telegram(channel, settings)
        if ok and count_items:
            suggestions.append(
                {"kind": "telegram", "value": channel, "items": count_items, "reason": f"cited {count}x in selected reports"}
            )
    return suggestions


def learn(
    store: Store,
    topic_id: str,
    settings: dict,
    *,
    runs: int = 10,
    auto_disable: bool = False,
    auto_add: bool = False,
) -> dict:
    metrics = source_metrics(store, topic_id, runs=runs)
    removals = [m.source for m in metrics if m.verdict == "remove"]
    suggestions = suggest_sources(store, topic_id, settings)
    if auto_disable and removals:
        disable_sources(topic_id, removals)
    if auto_add and suggestions:
        rss_urls = [s["value"] for s in suggestions if s["kind"] == "rss"]
        channels = [s["value"] for s in suggestions if s["kind"] == "telegram"]
        add_sources(topic_id, rss_urls=rss_urls, channels=channels)
    return {
        "metrics": [m.as_dict() for m in metrics],
        "removals": removals,
        "suggestions": suggestions,
        "disabled": auto_disable,
        "added": auto_add,
    }
